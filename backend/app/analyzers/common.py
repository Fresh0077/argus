"""分析器层的共享片段。

正则片段与证据裁剪是启发式线索层（``clues.py``）与规则层（``rules/``）
**共用**的定义。两处各写一份迟早会漂移，而"什么算字符串拼接""什么算动态实参"
这类判断一旦不一致，同一段代码在两层会得到互相矛盾的结论——那比只做一层更糟。

本模块只放无状态的常量和纯函数，不依赖任何其他分析器模块。
"""

from __future__ import annotations

#: 证据片段的最大长度。证据只保留最小必要上下文，
#: 不把整行之外的内容、更不把整个文件塞进响应。
MAX_SNIPPET_CHARS = 300


# ---------------------------------------------------------------------------
# 拼接 / 格式化
# ---------------------------------------------------------------------------

#: 字符串拼接或插值的算子。
#:
#: 刻意**不包含单独的 ``%s``**：它在参数化查询里是占位符，
#: 放进来会让 ``execute("... %s", (x,))`` 这类安全写法被误报。
#: 真正的 ``%`` 格式化（``"...%s" % x``）由 ``PERCENT_FORMATTING`` 识别。
#:
#: ``\.[ \t]*\$`` 覆盖 PHP 的 ``.`` 拼接（``"..." . $id``）。
#: 只能要求点号后面紧跟 ``$``：单独一个 ``.`` 在几乎所有语言里都合法
#: （成员访问、小数、方法链），放开来会让整个模式表失效。
INTERPOLATION = r"(?:\+|\.format\s*\(|\$\{|\{[$\w]|f['\"]|\.[ \t]*\$)"

#: ``'... = %s' % user_id`` 这类百分号格式化。
#: 关键区别：``%`` 出现在**字符串结束引号之后**，
#: 而参数化写法里的 ``%s`` 在引号内部——后者不能算作拼接。
PERCENT_FORMATTING = r"""['"][ \t]*%[ \t]*[(\w'"]"""

#: "这个值是被拼接或格式化构造出来的"——比 ``INTERPOLATION`` 更严格。
#:
#: 区别在 ``+``：这里要求它后面紧跟标识符、引号或左括号，所以 ``count + 1``
#: 不会命中（数字不在字符类里）。但 ``i + j`` **会**命中——不引入类型信息
#: 就分不清加法与拼接，而做类型推断超出了本层的定位。
#: 这是一处已知的高估：受影响的只有等级与置信度，以及拼接本身已可疑的场景。
STRING_CONSTRUCTION = (
    r"""\+[ \t]*(?:[A-Za-z_$@]|["'`]|\(\s*[A-Za-z_$@])"""
    r"""|\$\{|#\{|\.format\s*\(|f['"]|\.[ \t]*\$"""
    "|" + PERCENT_FORMATTING
)

#: "这一行里出现了动态的实参"，用于排除固定字面量参数的命令调用。
#:
#: 满足其一即可：调用括号后直接跟变量或变量下标、行内出现拼接/插值、
#: 或出现百分号格式化。这正是"固定命令参数不得误报"的落点。
DYNAMIC_ARGUMENT = (
    r"(?:\(\s*[$A-Za-z_][\w$\[\]'\"\->.]*\s*[,)]"
    r"|" + INTERPOLATION
    + r"|" + PERCENT_FORMATTING
    + r")"
)

#: SQL 语句开头的关键字。要求出现在行内，大小写不敏感。
#: ``select`` 与 ``from`` 之间的跨距有上限，避免退化成无界匹配。
SQL_KEYWORD = (
    r"(?i)\b(?:select\b[^\n]{0,300}?\bfrom\b"
    r"|insert\s+into\b|update\s+\w+\s+set\b|delete\s+from\b)"
)

#: 整行注释的行首标记。
#:
#: 只用来判断"**整行**是不是注释"，不做行内截断——因为 ``//`` 在 Python 里
#: 是整除运算符，按 ``//`` 截断会把 ``execute(sql + a // b)`` 的后半行吃掉，
#: 用一个漏报换一个误报并不划算。整行注释是最常见的那种情况
#: （文档示例、被注释掉的旧代码），代价小、收益直接。
#:
#: 刻意不含 SQL 的 ``--``：它在 JavaScript 里是自减运算符，``--i;`` 是正经语句。
COMMENT_PREFIXES = ("#", "//", "*", "/*", "<!--")

def snippet_of(line: str) -> str:
    """把一行代码裁剪成适合展示的证据片段。

    超长行按字符截断并加省略号——证据只保留最小必要上下文，
    不能被一行几万字符的压缩代码把响应撑大。
    """
    stripped = line.strip()
    if len(stripped) <= MAX_SNIPPET_CHARS:
        return stripped
    return stripped[: MAX_SNIPPET_CHARS - 1] + "…"
